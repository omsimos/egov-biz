const exampleUrl = "https://www.youtube.com/watch?v=AMeSZvb_4FA";

const form = document.querySelector("#extract-form");
const urlInput = document.querySelector("#youtube-url");
const extractButton = document.querySelector("#extract-button");
const exampleButton = document.querySelector("#example-button");
const status = document.querySelector("#status");
const resultSection = document.querySelector("#result");
const resultTitle = document.querySelector("#result-title");
const trackName = document.querySelector("#track-name");
const watchLink = document.querySelector("#watch-link");
const languageValue = document.querySelector("#language-value");
const segmentsValue = document.querySelector("#segments-value");
const durationValue = document.querySelector("#duration-value");
const transcript = document.querySelector("#transcript");
const downloadSrtButton = document.querySelector("#download-srt");
const downloadJsonButton = document.querySelector("#download-json");
const copyTextButton = document.querySelector("#copy-text");

let currentResult;

function formatDuration(totalSeconds) {
  const hours = Math.floor(totalSeconds / 3600);
  const minutes = Math.floor((totalSeconds % 3600) / 60);
  const seconds = Math.floor(totalSeconds % 60);

  return [hours, minutes, seconds].map((part) => String(part).padStart(2, "0")).join(":");
}

function renderTranscript(result) {
  currentResult = result;
  resultTitle.textContent = result.title;
  trackName.textContent = result.trackName;
  watchLink.href = result.watchUrl;
  languageValue.textContent = result.autogenerated
    ? `${result.languageCode} · auto-generated`
    : result.languageCode;
  segmentsValue.textContent = result.segments.length.toLocaleString();
  durationValue.textContent = formatDuration(result.durationSeconds);
  downloadSrtButton.href = `/api/transcript/${result.videoId}.srt`;
  downloadJsonButton.href = `/api/transcript/${result.videoId}.json`;

  transcript.replaceChildren(
    ...result.segments.map((segment) => {
      const row = document.createElement("div");
      row.className = "transcript-row";

      const timestamp = document.createElement("span");
      timestamp.className = "timestamp";
      timestamp.textContent = segment.timestamp;

      const text = document.createElement("p");
      text.textContent = segment.text;

      row.append(timestamp, text);
      return row;
    }),
  );

  resultSection.hidden = false;
  resultSection.scrollIntoView({ behavior: "smooth", block: "start" });
}

async function extractTranscript(url) {
  extractButton.disabled = true;
  exampleButton.disabled = true;
  resultSection.hidden = true;
  status.className = "status";
  status.textContent = "Reading YouTube’s transcript…";

  try {
    const response = await fetch("/api/transcript", {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ url }),
    });
    const body = await response.json();

    if (!response.ok || !body.ok) {
      throw new Error(body.error ?? "Transcript extraction failed");
    }

    renderTranscript(body.result);
    status.textContent = `${body.result.segments.length.toLocaleString()} segments ready.`;
  } catch (error) {
    status.className = "status error";
    status.textContent = error instanceof Error ? error.message : "Transcript extraction failed";
  } finally {
    extractButton.disabled = false;
    exampleButton.disabled = false;
  }
}

form.addEventListener("submit", (event) => {
  event.preventDefault();
  extractTranscript(urlInput.value);
});

exampleButton.addEventListener("click", () => {
  urlInput.value = exampleUrl;
  urlInput.focus();
});

copyTextButton.addEventListener("click", async () => {
  if (!currentResult) return;
  const text = currentResult.segments.map((segment) => segment.text).join(" ");
  await navigator.clipboard.writeText(text);
  copyTextButton.textContent = "Copied";
  window.setTimeout(() => {
    copyTextButton.textContent = "Copy text";
  }, 1_500);
});
